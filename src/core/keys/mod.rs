//! 两种「key」的纯逻辑。
//!
//! ⚠️⚠️ **本仓有两个都叫 key 的东西，方向相反，读之前先分清**：
//! - **上游 key**：我们**持有**、拿去打 Agnes 上游的那一把（池子里的）。
//! - **对外 API 密钥（`sk-*`）**：我们**签发**、下游客户拿来打我们的那一把。
//!
//! 把它们读混的后果是把上游 key 的明文当成「自家签发的」展示出去。
//!
//! # 两个文件
//!
//! | 文件 | 放什么 |
//! |---|---|
//! | [`view`] | **上游 key** 的面板投影（🔴 永不含明文）、`key_bucket`、`mask_key` |
//! | [`api_keys`] | **我们签发的 `sk-*`**：摘要、掩码、分档、`find_by_digest`、三档窄化 |
//!
//! 三条红线（判据都已经买过单，两个文件里各自还有更细的说明）：
//! - 🔴 [`view::mask_key`] 必须按 `char` 切，**不许 `&s[..5]`** —— 后者在多字节字符上
//!   panic，而 key 明文是不受控输入（铸号那条路存进去的可疑 key 可能不是 ASCII）。
//! - 🔴 两个 `matches_*` **绝不能变成预言机**：上游那边不许匹配明文，
//!   我们签发的这边不许匹配摘要。
//! - 🔴 [`api_keys::find_by_digest`] 的循环**不许短路**（表内位置那一维靠它挡）。
//!
//! ⚠️ **签发（铸币）不在这里**：那要 CSPRNG，而零 IO 岛的立身之本就是「同样的输入
//! 永远给同样的输出」。铸币住在 `apikey/`。

