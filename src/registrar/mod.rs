//! 注册机（自动铸 key 补池）。**本仓独有的一块，kiro2api 没有任何可参照物。**
//!
//! # 为什么它值得单独一期
//!
//! kiro2api **没有任何可参照物**：kiro 的 key 是用户自己的登录凭据，
//! agnes 的 key 是注册机铸出来的。这一块是本仓独有的、也是最难的一块
//! （TS 版 10 个文件 2,704 行：通道选择、邮箱、域名台账、跨轮退避、验证码提取）。
//!
//! # 这一块永远排第一的那条规矩：**它装不起来时网关照常活着**
//!
//! 🔴 这不是一句愿望，是一条 🔴 判据（`config-degrade`，4 格），
//! 它记录的是**真机 74% 请求 500 那次事故**：注册机装配失败把整个进程带崩。
//! ⇒ 规矩写死：**注册机的任何装配失败只记日志，绝不阻断网关启动，
//! 更不许让转发路径感知到它。**
//!
//! 📜 这里曾写着「本轮不建任何占位类型」。那条已经不再是「本轮」的事，
//! 但它立的规矩照旧：**一个空的 `RegistrarConfig` 会让「注册机配好了吗」
//! 在面板上得到一个假答案**（`stored: null` / `effective: {...}` 这种自相矛盾的四元组）。
//! **没有，就如实地没有。**
//!
//! # 逐个模块记的落地情况（别靠 `pub mod` 的行数猜）
//!
//! - ✅ [`code`] —— 验证码提取（TS 版 `registrar/code.ts` 160 行）。
//!   纯逻辑、零 IO，先落它是因为它最独立，而且**它是全组里最容易在移植中丢细节的一块**：
//!   三条正则的上界各有各的论证，规格 §10.9 记着 TS 那边**在同一个坑里栽过两次**。
//! - ✅ [`url`] —— 出站地址脱敏与四个错误消息模板（TS 版 `registrar/url.ts` 285 行）。
//!   同样是纯逻辑。它是这一组里**唯一直接关系到凭据泄漏**的一块：
//!   规格 §10.10 记着一个**实测出来的洞** —— 运行时在「构造请求」那一步就抛，
//!   而它的 message 里带着完整的原始 URL，于是口令绕过全部脱敏进事件板块与容器 stdout。
//! - ✅ [`domain_ledger`] —— 域名台账（TS 版 686 行）。**判死的判据是启发式的**，
//!   三层防线压着那个必然存在的误判：两跳 + 一轮最多学 1 条 + 排序永不 filter。
//! - ✅ [`backoff`] —— 跨轮指数退避（TS 版 248 行）。它治的是
//!   「窗口里每打一次就把窗口续一次」那个缺陷，**而光靠本轮中止不够**。
//! - ✅ [`types`] —— 时间常量与它们之间那几条必须成立的关系（TS 版 150 行）。
//!   **每个数都压着一条失败形态**，而且其中一条原注释在规格复核时被判定为假
//!   （「多出来的 10 秒留给 elapsed」），订正一并带过来了。
//! - ✅ [`config`] —— 配置装载（TS 版 615 行，注册机最大的单文件）。
//!   **装载器零 panic**（唯一豁免是消费方护栏 [`config::require_channel`]）：
//!   注册机是可选子系统，它缺凭据不该让转发、`/health`、面板一起死。
//! - ✅ [`tender`] —— 补池一轮的编排（TS 版 889 行，注册机的核心）。
//!   **不是零 IO 的**，但依赖全部从外面注进来 —— 这一轮里每一条分支都对应
//!   一次真实的上游请求或一次真实的落盘，而它们的正确性只有在
//!   **能精确控制时钟与上游回话**的前提下才验得了。
//! - ✅ [`mint`] —— 单次铸号（TS 版 388 行）。**走到后三步的失败是最贵的** ——
//!   邮箱已真的建出来、验证码已真的要过一次、上游那边甚至可能已经把账号建好了，
//!   所以那三步各有自己的诊断（见 [`mint::step_message`]）。
//! - ✅ [`fetch`] —— 注册机所有出站请求的**唯一出口**（TS 版 48 行）。
//!   🔴 脱敏落在**「发请求这件事」**上，而不是「非 2xx」那一支：
//!   压根没发出去时，运行时抛的那个错误消息里**可能带着完整的原始 URL**。
//!   做成一个出口而不是每个调用点各写一次，是因为后者的失败形态是
//!   **「下一个人新加的那一处忘了包」**，而那种遗漏不会有任何东西变红。
//! - ✅ [`agnes`] —— Agnes 站点四步（TS 版 195 行）。
//!   🔴 四步统一把**状态码与整份正文**交出去 —— 上一版把它们在函数边界丢光了，
//!   于是**四种真因在面板上长得一模一样**。
//!
//! - ✅ [`mailbox`] —— 两条邮箱通道的真实实现（TS 版 300 + 260 行）。
//!   🔴 YYDS 那条**「收信按 address、删除按 id」是真机实测的契约** ——
//!   此前存的是 address，删邮箱因此每次都 404，**「用完即删」从未真正生效**。
//!
//! 🔴 **十个模块全部落地。** 剩下的是**接线**（把它们拼进 `wire`、
//! 把三条 `/admin/api/registrar/*` 端点从占位换成真实现），不是新写业务规则。
//!
//! 🔴 **三条 `/admin/api/registrar/*` 端点今天仍是占位**（`503 not_wired`，见
//! [`crate::admin::registrar`]）。落了一个模块**不等于**功能可用 ——
//! 在整轮跑得通之前，那三条一个字都不许改成「已接线」。

