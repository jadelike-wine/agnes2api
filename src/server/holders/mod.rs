//! 「持有者」：带 TTL 的快照。两个，**各自回答一条对外承诺**。
//!
//! | 持有者 | TTL | 那条承诺 |
//! |---|---|---|
//! | [`config_holder`] | 30 秒 | 「面板改完配置，最多 30 秒生效」 |
//! | [`apikey_holder`] | 5 分钟 | 「面板停用一把子密钥，它最多还能再用约 5 分钟」 |
//!
//! 两个都建在 [`crate::core::refreshable::Refreshable`] 这一个原语上，**不许各写一份**：
//! 它们回答的是同一个问题「刚改完，什么时候能看见？」，各写一份必然漂移出两套语义
//! （而漂移的那一格总是最少见、最难复现的那一格）。
//!
//! 两者最要紧的区别写在各自的模块头上：
//! - `ConfigHolder` 的**首次装载失败必须抛**（缺 `GATEWAY_TOKEN` 拒绝服务是不变量）；
//! - `ApiKeyHolder` 的**冷启动读失败必须降级成一份合法快照**（否则每个错口令请求一次存储读）。
//!   两条方向相反，**都是对的** —— 因为一个是启动门禁，一个在未鉴权热路径上。

pub mod apikey_holder;
pub mod config_holder;
