//! 管理面 REST（`/admin/api/*`）。
//!
//! # 路径前缀保留 `/admin/api/*`，不改成 kiro 的 `/api/admin/*`
//!
//! 1. 它是**已发布的对外契约**：五语言 API.md 逐条写着它。
//! 2. 用户那条「完全对标 kiro2api」的规则管的是**功能与面板 UI**，URL 不在其中。
//! 3. **成本不对称**：P2 抄 kiro 面板时改的是前端 baseURL 一个常量；
//!    改后端要动五语言文档 N 处 + 破坏既有部署。
//! 4. 若 P2 实测发现 kiro 的面板 JS 里散着硬编码，**再加一层 `/api/admin/*` 别名** ——
//!    kiro 自己就同时挂新旧两套。这是可加项，不是必须先定的。
//!
//! # 🔴 一条先摆在这里的硬规则：**路由表绝不许随运行时配置变化**
//!
//! 「注册机没开」「Tier-2 没开」「没接线」一律是 handler 里的一个状态码，
//! **不是「这条路由不存在」**。理由：枚举式鉴权矩阵会因为夹具恰好关着某功能
//! 而让那几条端点从矩阵里**静默消失**，于是一整族鉴权判据在不知不觉中失去对象。
//!
//! ⇒ 33 条方法级端点**全部注册**，实现深度分三档：完整实现 / 薄版（如实回
//! `tier:"off"`，**不是 503**）/ 占位 `503 {reason:"not_wired"}`。
//! ⚠️ 用量那两条回 503 会让面板把「运维没打开统计」渲染成「后端坏了」。
//!
//! # 已落地的组
//!
//! 🔴 **这一段是给下一个接手的人看的事实清单，不是计划表** ——
//! 本仓把「文档是真源、改了就是改契约」当纪律，这里写错一句就是直接误导。
//! **以下面那几行 `pub mod` 声明为准**，加了模块就把它写进来。
//!
//! - [`keys`] —— `/admin/api/keys*` 那九条（列表 / 导入 / 批量 / 清空 / reveal /
//!   删除 / PATCH / 用量 / 验活）。⚠️ 它**暂时**兼管两件本该住在别处的东西：
//!   [`keys::ProbeGuard`]（归将来的 `probe_guard.rs`）与三个 `KeyPoolRepo` 上还不存在的
//!   批量方法 —— 理由与搬迁路径写在那个文件的文件头，别当成边界被推翻了。
//! - [`capabilities`] —— `GET /admin/api/capabilities`（这个部署有什么、没有什么）。
//! - [`config`] —— 设置页那五条（`GET` / `PUT` / 干跑 / 清凭据 / 重置），
//!   外加四元组快照 [`config::snapshot_of`]：它同时是 [`overview`] 那格 `degraded` 的来源。
//! - [`events`] —— 事件板块。
//! - [`models`] —— 协议目录 / 模型目录（`PROTOCOLS` / `MEDIA_ENDPOINTS` /
//!   `MODEL_CATALOG`，面板四个消费者的单一真源）与逐模型连通性测试。
//! - [`overview`] —— 概览页的唯一取数端点。
//! - [`session`] —— `GET /admin/api/session`（登录探针，**恰好两格**：`ok` / `version`）。
//! - [`upstream_models`] —— `GET /admin/api/upstream/models`（真打一次上游问它此刻有哪些
//!   模型）。⚠️ 它与 [`models`] 那条**并存**，回答的是两个问题，别拿它去替目录。
//! - [`usage`] —— 用量那两条（Tier-2 关着时 **200 + `tier:"off"`**，不是 503）。
//! - [`registrar`] —— 注册机那三条（补池 / 状态 / 通道测试）。
//!   🔴 **三条一律现读配置**：面板是这份配置的编辑器，读启动快照等于
//!   「保存成功、界面照旧、按钮照旧」。没接注册机的部署仍回
//!   `503 {reason:"not_wired"}` —— 路由表不许随运行时配置变化，见上一节。
//!
//! # 🔴 管理闸**不在本目录**
//!
//! 它落在 [`crate::server::middleware::admin_auth`]：只认 `X-Admin-Key`、
//! 四条口令形状规则（首尾空白 / 送不出去的字符 / 太短 / 与网关口令相同）、
//! 常数时间比较、两把口令相同时的 **503**（🔴 不是 401 —— 401 会让面板把运维
//! 踢回登录闸去重填一个本来就对的口令）。
//! ⚠️ **别在本目录下再造一个 `auth.rs`**：两份口令判定就是两套规则。
//!
//! 🔴 一条现在就要记住的：`ADMIN_TOKEN` 未设时**整棵 `/admin` 树不注册 → 404**，
//! 而不是 401 —— **不泄漏「这里有个后台」**。
//!
//! # 还没有的
//!
//! `probe_guard.rs`（[`keys::ProbeGuard`] 的将来归宿：按 kind 分槽的两道闸，
//! **一把 guard 交给全部探测端点** —— 今天它已经是进程级单例，搬家是挪位置不是改形态）。
//!
//! ⚠️ 注册机**已经不在这一节里了**：跨副本存储锁、补池、通道测试都已落地
//!（锁在 [`crate::registrar::runtime::acquire_tend_lock`]，
//! 不是本目录下的 `tend_lock.rs`）。
//!
//! 🟢 **一条登记在案、现已收口的缺口**：护栏的「放开」只挂在 RAII 上
//! （[`keys::ProbeGuard::acquire`] 交出 [`keys::ProbeLease`]，drop 即放开，
//! **请求被取消那一支也覆盖得到**）—— [`keys`] 的验活、[`models`] 的连通性测试、
//! [`upstream_models`] 这三条探测端点**今天都走它**，手动配对 `try_acquire` /
//! `release` 在本目录下**一个调用点都不剩**（`release` 只在租约的 drop 里）。
//! 🔴 **新开的探测端点一律走租约**：手写配对覆盖不到「请求被取消」那一支 ⇒
//! 客户端一断开那个 kind 就**永久**卡在「在飞」，而探测端点的 kind 多是**常量**
//! （不是逐把 key 一格）⇒ 卡住的是整颗按钮，且这道闸不像最小间隔那道会自愈。

