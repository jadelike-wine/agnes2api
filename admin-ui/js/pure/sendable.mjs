/**
 * 管理口令的字符集判定。**前后端共用同一份定义。**
 *
 * 🔴 **后端那份是真源**：`src/server/middleware/admin_auth.rs` 里的
 * `token.bytes().all(|b| (0x20..=0x7e).contains(&b))`。
 * 这一份是它在浏览器里的孪生体，由 `src/webui/mod.rs` 的
 * `the_panel_charset_matches_the_backend_byte_for_byte` 那一格把**下面这条正则的
 * 上下界**与 Rust 那条区间逐字对账 —— 改一边而忘了另一边会当场红。
 *
 * **前端这一半必须有**：后端只在启动时看得到自己的口令，看不到用户粘了什么；
 * 送出去也没用，而且会在服务端留下一条无意义的登录失败记录。
 *
 * ── 字符集是 `0x20–0x7E`，理由分三段，性质不同，别混着说 ────────────────
 *
 * **(a) 码点 > U+00FF，以及 NUL / LF / CR —— 物理，发生在浏览器。**
 *   `new Headers().set()` 直接抛 `TypeError`（Fetch 规范：头值是 ByteString，
 *   码点 > 255 转不过去；NUL/LF/CR 过不了头值校验）。
 *   这种口令会装出一棵 200 但永远进不去的面板：用户看到「网络错误」，
 *   而服务端**连一条登录失败都没有**（请求压根没发出来）。
 *
 * **(b) `0x01–0x08`、`0x0B`、`0x0C`、`0x0E–0x1F`、`0x7F` —— 物理，但发生在服务端解析器。**
 *   浏览器**送得出去**，HTTP 解析器才拒（400 Bad Request）。
 *   ⚠️ **TAB `0x09` 是例外，它不在这一段，落在 (c)。** HTAB 是 RFC 9110 里合法的
 *   field-value 字符，解析器收它。
 *
 * **(c) TAB `0x09` 与整段 `0x80–0xFF` —— 送得出去，也真的能用。排除它们是取舍，是口味，不是物理。**
 *   · **TAB**：它是**不可见字符**，粘进 `.env` 或 secret 里没人看得见。
 *   · **`0x80–0xFF`**：环境变量按 UTF-8 解、HTTP 头值按 Latin-1 解，两边碰巧在
 *     U+0080–U+00FF 这段对上是**实现细节**，不是规范承诺；且 RFC 9110 已把
 *     obs-text（0x80–0xFF）标为**弃用**，中间件/反代对它的处置各不相同。
 *     而非 ASCII 口令**不是一个有价值的形态**（它不比同长度的 ASCII 更强）。
 *
 * ⚠️ **空格 `0x20` 是放行的**，别再把它划回去：空格是纯 ASCII、跨运行时零编码歧义，
 * 而带空格的 passphrase（`correct horse battery staple`）是**有价值的常见形态**。
 * **判据不是「是不是口味」，而是「这个限制换来的稳健性值不值它挡掉的形态」。**
 *
 * 这个目录下的文件受三条硬规则约束：顶层只许 `export`、禁 `import`、
 * 禁出现 `document` / `window`。
 */

/**
 * 量词是 `*`：这条规则说的是「不含送不出去的字符」，**非空不是它的职责**
 *（后端归 `too_short`，前端归 `login.empty`，两边各自的上游判断都先把空串接走了）。
 *
 * ⚠️ 前端写 `+` 而后端写 `*` 是一处**多余**的不对称：它让「两边一致」这句话必须带一个
 * 空串的例外，护栏也就只能做到「除了空串以外一致」。统一成 `*`。
 */
const SENDABLE_RE = /^[\x20-\x7e]*$/;

/** 这个字符串能不能被客户端送出去、并被服务端解析器收下。 */
export function sendable(s) {
  return SENDABLE_RE.test(s);
}
